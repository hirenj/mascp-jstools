#!/usr/bin/env node
// Regenerates js/lib/biomsa-source.js from the currently-installed `biomsa`
// package. Run this (`node scripts/generate-biomsa-source.js`) whenever the
// `biomsa` dependency version in package.json is bumped - the generated
// file is committed to the repo rather than built on every install, so it
// ships correctly regardless of how a consumer installs this package (git
// dependency, npm registry, local symlink/workspace) without relying on
// lifecycle-script timing.
//
// Why a generated plain-string module instead of importing biomsa.js
// directly: ClustalRunner.js needs biomsa's raw UMD source TEXT (not the
// evaluated module) to drop verbatim into a classic Worker's Blob, so the
// worker never depends on bundler-specific `new Worker(new URL(...))`
// module-worker support. Previously that text was obtained via webpack's
// inline `!!raw-loader!` syntax, which silently required every consumer's
// own bundler to have `raw-loader` resolvable at build time - a real
// runtime dependency hiding in source code, not just this package's own
// build tooling. A plain `export default "...."` module needs no loader at
// all, in any bundler (webpack, Vite, esbuild, Rollup) or plain Node.
'use strict';

const fs = require('fs');
const path = require('path');

const biomsaPath = require.resolve('biomsa');
const source = fs.readFileSync(biomsaPath, 'utf8');
const biomsaVersion = require('biomsa/package.json').version;

const outPath = path.join(__dirname, '..', 'js', 'lib', 'biomsa-source.js');
const header = `// Auto-generated by scripts/generate-biomsa-source.js from
// biomsa@${biomsaVersion} (${path.relative(path.join(__dirname, '..'), biomsaPath)}) - do not edit directly.
// Re-run that script after bumping the biomsa dependency in package.json.
`;

fs.writeFileSync(outPath, `${header}export default ${JSON.stringify(source)};\n`);

console.log(`Wrote ${path.relative(process.cwd(), outPath)} from biomsa@${biomsaVersion}`);
